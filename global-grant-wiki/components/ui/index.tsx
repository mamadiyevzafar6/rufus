    variants: {
      variant: {
        default: 'bg-primary/15 text-primary ring-primary/30',
        secondary: 'bg-secondary text-secondary-foreground ring-border',
        outline: 'text-foreground ring-border',
      },
    },
    defaultVariants: { variant: 'default' },
